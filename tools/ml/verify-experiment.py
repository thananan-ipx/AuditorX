"""Verify trusted local coursework artifacts, saved metrics and HTTP inference parity."""
import argparse
import csv
import hashlib
import importlib.util
import json
from pathlib import Path
import pickle
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "prediction"))
from app import Features, TreeModel, create_app
from fastapi.testclient import TestClient

spec = importlib.util.spec_from_file_location("coursework", Path(__file__).with_name("train-coursework.py"))
course = importlib.util.module_from_spec(spec)
spec.loader.exec_module(course)


def verify(folder):
    metrics = json.loads((folder / "metrics.json").read_text(encoding="utf-8"))
    splits = {}
    for split in ("train", "validation", "test"):
        with (folder / f"{split}.csv").open(encoding="utf-8-sig", newline="") as handle:
            splits[split] = list(csv.DictReader(handle))
    if {s: len(rows) for s, rows in splits.items()} != metrics["split_rows"]:
        raise ValueError("Saved split sizes differ from metrics")
    groups = [{r.get("clone_group") or r["case_family"] for r in rows} for rows in splits.values()]
    if groups[0] & groups[1] or groups[0] & groups[2] or groups[1] & groups[2]:
        raise ValueError("Source family/clone group crosses an evaluation split")
    for filename, key in (("input.csv", "input_sha256"),
                          ("additional-training-input.csv", "additional_input_sha256"),
                          ("source-manifest.json", "source_manifest_sha256")):
        if metrics.get(key) and hashlib.sha256((folder / filename).read_bytes()).hexdigest() != metrics[key]:
            raise ValueError(f"Checksum mismatch: {filename}")
    x, y = course.xy(splits["test"])
    for name in ("decision_tree", "random_forest"):
        # Operator tool for artifacts generated by this repository; never request uploads.
        with (folder / f"{name}.pkl").open("rb") as handle:
            model = pickle.load(handle)
        if course.scores(y, model.predict(x)) != metrics["test_results"][name]:
            raise ValueError(f"Saved model does not reproduce metrics: {name}")
    with (folder / "decision_tree.pkl").open("rb") as handle:
        model = pickle.load(handle)
    served = TreeModel(folder / "service-model.json")
    if served.data["source_model_sha256"] != hashlib.sha256((folder / "decision_tree.pkl").read_bytes()).hexdigest():
        raise ValueError("Serving artifact is not from the saved Decision Tree")
    rows = [row for split in splits.values() for row in split]
    x, _ = course.xy(rows)
    expected = model.predict(x).tolist()
    if [served.predict(Features(**row)) for row in x] != expected:
        raise ValueError("Data-only serving tree differs from sklearn")
    with TestClient(create_app(folder / "service-model.json")) as client:
        response = client.post("/predict", json={"items": [
            {"fingerprint": row["finding_fingerprint"], "features": features} for row, features in zip(rows, x)]})
        if response.status_code != 200:
            raise ValueError(f"HTTP prediction failed: {response.status_code}")
        body = response.json()
        if (body["model_version"] != metrics["experiment"] or body["training_rows"] != len(splits["train"])
                or [p["priority"] for p in body["predictions"]] != expected):
            raise ValueError("HTTP inference differs from saved experiment")
    return {"experiment": metrics["experiment"], "verified_rows": len(rows),
            "split_rows": metrics["split_rows"], "model_sha256": served.digest,
            "human_ground_truth": False}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--experiment-dir", type=Path, default=ROOT / "output/ml/coursework-v3")
    args = parser.parse_args()
    print(json.dumps(verify(args.experiment_dir), indent=2))


if __name__ == "__main__":
    main()
